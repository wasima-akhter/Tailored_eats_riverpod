class MealIngredient {
  final String item;
  final String quantity;
  final double calories;
  final double proteinG;
  final double carbsG;
  final double fatG;

  const MealIngredient({
    required this.item,
    required this.quantity,
    required this.calories,
    required this.proteinG,
    required this.carbsG,
    required this.fatG,
  });
}
